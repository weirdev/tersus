module LlvmRuntime
    ( runtimeSource
    ) where

-- The C runtime that the emitted LLVM IR calls: what the program does that is not an instruction. `tersus build` writes
-- it to a temporary file beside the IR and compiles both with clang.
--
-- A value is held as C holds it (Mir.layoutOf): an Int, the address of a function and an address are 8 bytes, a Bool and a Byte 1, a
-- fixed-width integer its bits over 8. A struct, an enum and an array are their bytes, held in the frame of a function, in a field or in
-- memory at an address: a struct its fields at the offsets of C, an enum a U32 that says the variant and then the fields of that variant,
-- an array its elements. What is on the heap is memory at an address, which only a struct of the library or of the program holds: a list
-- is the struct List of lib/lists.tersus, and a Box the struct Box of lib/box.tersus (or a List, for a Box of an array), and each
-- is freed by its drop.
-- The runtime does none of that by the type of a value: the emitted code makes a function per type that frees,
-- copies and prints a value of it, and the runtime is what talks to the system and the memory of the heap.
runtimeSource :: String
runtimeSource =
    unlines
        [ "#include <pthread.h>"
        , "#include <stdint.h>"
        , "#include <stdio.h>"
        , "#include <stdlib.h>"
        , "#include <string.h>"
        , "#include <sys/resource.h>"
        , "#include <unistd.h>"
        , ""
        , "static void fail(const char *message);"
        , ""
        , "// Whether the program has started a thread (set before the first one starts, and never cleared)"
        , "static int threads_started = 0;"
        , ""
        , "// What each thread has of its own (the program's threads, MirThreads): in the static block of the executable, so a use"
        , "// is one load"
        , "#define THREAD_LOCAL __thread __attribute__((tls_model(\"initial-exec\")))"
        , ""
        , "// The values of the heap come from here. Compiled with -DTERSUS_CHECK, every block is recorded and a block that is freed"
        , "// is filled with 0xDD and kept (so that a use of it reads that), a block freed twice is reported, and so is a block"
        , "// that is still there when the program ends. The tests build that way."
        , "#ifdef TERSUS_CHECK"
        , "typedef struct Block {"
        , "    uint64_t state;"
        , "    uint64_t size;"
        , "} Block;"
        , ""
        , "#define BLOCK_LIVE 0x11fe11fe11fe11feULL"
        , "#define BLOCK_FREED 0xdeaddeaddeaddeadULL"
        , ""
        , "static int64_t live_blocks = 0;"
        , ""
        , "static void check_failed(const char *message) {"
        , "    fprintf(stderr, \"Memory check failed: %s\\n\", message);"
        , "    _exit(99);"
        , "}"
        , ""
        , "static void check_leaks(void) {"
        , "    int64_t live = __atomic_load_n(&live_blocks, __ATOMIC_RELAXED);"
        , "    if (live != 0) {"
        , "        fprintf(stderr, \"Memory check failed: %lld values were not freed\\n\", (long long)live);"
        , "        _exit(99);"
        , "    }"
        , "}"
        , ""
        , "__attribute__((constructor)) static void start_checking(void) {"
        , "    atexit(check_leaks);"
        , "}"
        , ""
        , "static void *allocate(size_t size) {"
        , "    Block *block = malloc(sizeof(Block) + size);"
        , "    if (block == NULL) fail(\"Out of memory\");"
        , "    block->state = BLOCK_LIVE;"
        , "    block->size = size;"
        , "    __atomic_fetch_add(&live_blocks, 1, __ATOMIC_RELAXED);"
        , "    return block + 1;"
        , "}"
        , ""
        , "static void release(void *memory) {"
        , "    Block *block = (Block *)memory - 1;"
        , "    if (block->state != BLOCK_LIVE) check_failed(\"a value is freed twice, or what is freed is not a value\");"
        , "    block->state = BLOCK_FREED;"
        , "    memset(memory, 0xDD, (size_t)block->size);"
        , "    __atomic_fetch_sub(&live_blocks, 1, __ATOMIC_RELAXED);"
        , "}"
        , ""
        , "static void *reallocate(void *memory, size_t size) {"
        , "    Block *block = (Block *)memory - 1;"
        , "    if (block->state != BLOCK_LIVE) check_failed(\"a value that was freed is grown\");"
        , "    void *grown = allocate(size);"
        , "    memcpy(grown, memory, block->size < size ? (size_t)block->size : size);"
        , "    release(memory);"
        , "    return grown;"
        , "}"
        , "#elif defined(TERSUS_SYSTEM_MALLOC)"
        , "// The heap of the system itself, for a build that valgrind runs: it watches malloc and free, which the blocks below hide."
        , "static void *allocate(size_t size) {"
        , "    void *memory = malloc(size);"
        , "    if (memory == NULL) fail(\"Out of memory\");"
        , "    return memory;"
        , "}"
        , ""
        , "static void release(void *memory) {"
        , "    free(memory);"
        , "}"
        , ""
        , "static void *reallocate(void *memory, size_t size) {"
        , "    void *grown = realloc(memory, size);"
        , "    if (grown == NULL) fail(\"Out of memory\");"
        , "    return grown;"
        , "}"
        , "#else"
        , "// Small values, which are most of them, come from lists of free blocks of a few sizes, cut from large chunks: a program"
        , "// makes and frees many of them, and malloc's own bookkeeping cost more than the program's work. A block has a header of"
        , "// 16 bytes before it: its size class, or 0 for a block of malloc's. The chunks are given back when the program ends."
        , "// Each thread has lists and a chunk of its own (a Heap), and a block goes to the lists of the thread that frees it; only"
        , "// taking a new chunk is shared. The main thread's heap is a global, which a program that starts no thread uses without"
        , "// looking up what is the thread's own: that look is a load at the thread's base on every allocation and free, which costs"
        , "// the compiler's own programs a few percent."
        , "#define SMALL_STEP 16"
        , "#define SMALL_CLASSES 32"
        , "#define CHUNK_BYTES (1 << 20)"
        , ""
        , "typedef struct Header {"
        , "    uint64_t size_class;"
        , "    uint64_t size;"
        , "} Header;"
        , ""
        , "typedef struct Heap {"
        , "    void *free_blocks[SMALL_CLASSES + 1];"
        , "    unsigned char *chunk_next;"
        , "    unsigned char *chunk_end;"
        , "} Heap;"
        , ""
        , "// (each chunk starts with the address of the chunk before it)"
        , "static void *last_chunk = NULL;"
        , "static pthread_mutex_t chunk_lock = PTHREAD_MUTEX_INITIALIZER;"
        , "static Heap main_heap;"
        , "// (a thread that the program starts points its own at thread_heap)"
        , "static THREAD_LOCAL Heap thread_heap;"
        , "static THREAD_LOCAL Heap *own_heap = &main_heap;"
        , ""
        , "static void free_chunks(void) {"
        , "    while (last_chunk != NULL) {"
        , "        void *earlier = *(void **)last_chunk;"
        , "        free(last_chunk);"
        , "        last_chunk = earlier;"
        , "    }"
        , "}"
        , ""
        , "static void *allocate_from(Heap *h, size_t size) {"
        , "    size_t size_class = size == 0 ? 1 : (size + SMALL_STEP - 1) / SMALL_STEP;"
        , "    if (size_class <= SMALL_CLASSES) {"
        , "        void *block = h->free_blocks[size_class];"
        , "        if (block != NULL) {"
        , "            h->free_blocks[size_class] = *(void **)block;"
        , "            return block;"
        , "        }"
        , "        size_t total = sizeof(Header) + size_class * SMALL_STEP;"
        , "        if (h->chunk_next == NULL || (size_t)(h->chunk_end - h->chunk_next) < total) {"
        , "            unsigned char *chunk = malloc(CHUNK_BYTES);"
        , "            if (chunk == NULL) fail(\"Out of memory\");"
        , "            pthread_mutex_lock(&chunk_lock);"
        , "            if (last_chunk == NULL) atexit(free_chunks);"
        , "            *(void **)chunk = last_chunk;"
        , "            last_chunk = chunk;"
        , "            pthread_mutex_unlock(&chunk_lock);"
        , "            h->chunk_next = chunk + SMALL_STEP;"
        , "            h->chunk_end = chunk + CHUNK_BYTES;"
        , "        }"
        , "        Header *header = (Header *)h->chunk_next;"
        , "        h->chunk_next += total;"
        , "        header->size_class = size_class;"
        , "        return header + 1;"
        , "    }"
        , "    Header *header = malloc(sizeof(Header) + size);"
        , "    if (header == NULL) fail(\"Out of memory\");"
        , "    header->size_class = 0;"
        , "    header->size = size;"
        , "    return header + 1;"
        , "}"
        , ""
        , "static void release_to(Heap *h, void *memory) {"
        , "    if (memory == NULL) return;"
        , "    Header *header = (Header *)memory - 1;"
        , "    if (header->size_class == 0) {"
        , "        free(header);"
        , "        return;"
        , "    }"
        , "    *(void **)memory = h->free_blocks[header->size_class];"
        , "    h->free_blocks[header->size_class] = memory;"
        , "}"
        , ""
        , "static void *allocate(size_t size) {"
        , "    return allocate_from(__builtin_expect(threads_started, 0) ? own_heap : &main_heap, size);"
        , "}"
        , ""
        , "static void release(void *memory) {"
        , "    release_to(__builtin_expect(threads_started, 0) ? own_heap : &main_heap, memory);"
        , "}"
        , ""
        , "static void *reallocate(void *memory, size_t size) {"
        , "    if (memory == NULL) return allocate(size);"
        , "    Header *header = (Header *)memory - 1;"
        , "    if (header->size_class != 0) {"
        , "        size_t room = header->size_class * SMALL_STEP;"
        , "        if (size <= room) return memory;"
        , "        void *grown = allocate(size);"
        , "        memcpy(grown, memory, room);"
        , "        release(memory);"
        , "        return grown;"
        , "    }"
        , "    if (size <= SMALL_CLASSES * SMALL_STEP) return memory;"
        , "    Header *grown = realloc(header, sizeof(Header) + size);"
        , "    if (grown == NULL) fail(\"Out of memory\");"
        , "    grown->size = size;"
        , "    return grown + 1;"
        , "}"
        , "#endif"
        , ""
        , "// (with _exit, since other threads may still run: what exit runs at the end, the frees of the heap and its check, is not run)"
        , "static void fail(const char *message) {"
        , "    fflush(stdout);"
        , "    fprintf(stderr, \"Evaluation failed: %s\\n\", message);"
        , "    fflush(stderr);"
        , "    _exit(1);"
        , "}"
        , ""
        , "// An Int left its 64 bits: the same message and exit status as `tersus run`"
        , "void tersus_overflow(void) {"
        , "    fail(\"Integer overflow\");"
        , "}"
        , ""
        , "// writeByte(b): the byte b to the standard output, with what the program prints at the end. It is the value of the call."
        , "int64_t tersus_writeByte(int64_t byte) {"
        , "    putchar((int)(byte & 255));"
        , "    return byte;"
        , "}"
        , ""
        , "// writeError(b): the same for the standard error"
        , "int64_t tersus_writeError(int64_t byte) {"
        , "    fputc((int)(byte & 255), stderr);"
        , "    return byte;"
        , "}"
        , ""
        , "// The arguments of the program, which main gives to the runtime"
        , "static int program_argc = 0;"
        , "static char **program_argv = NULL;"
        , ""
        , "void tersus_init(int argc, char **argv) {"
        , "    program_argc = argc;"
        , "    program_argv = argv;"
        , "}"
        , ""
        , "// argCount(): the number of arguments, not counting the name of the program"
        , "int64_t tersus_argCount(void) {"
        , "    return program_argc > 0 ? (int64_t)program_argc - 1 : 0;"
        , "}"
        , ""
        , "// argByte(i, j): the byte j of argument i, or -1 when there is no such argument or byte"
        , "int64_t tersus_argByte(int64_t i, int64_t j) {"
        , "    if (i < 0 || i >= tersus_argCount() || j < 0) return -1;"
        , "    const char *argument = program_argv[i + 1];"
        , "    for (int64_t k = 0; k < j; k++) {"
        , "        if (argument[k] == 0) return -1;"
        , "    }"
        , "    return argument[j] == 0 ? -1 : (int64_t)(unsigned char)argument[j];"
        , "}"
        , ""
        , "// The files: a path is built a byte at a time, and then the file at it is loaded (and read a byte at a time) or a file that was built a byte at"
        , "// a time is stored there. A path is at most 4095 bytes, and ends at a byte that is 0. Each thread builds its own."
        , "static THREAD_LOCAL unsigned char path_buffer[4096];"
        , "static THREAD_LOCAL size_t path_length = 0;"
        , "static THREAD_LOCAL unsigned char *loaded_file = NULL;"
        , "static THREAD_LOCAL size_t loaded_length = 0;"
        , "static THREAD_LOCAL unsigned char *stored_file = NULL;"
        , "static THREAD_LOCAL size_t stored_length = 0;"
        , "static THREAD_LOCAL size_t stored_capacity = 0;"
        , ""
        , "int64_t tersus_pathByte(int64_t byte) {"
        , "    if (path_length < 4095) path_buffer[path_length++] = (unsigned char)(byte & 255);"
        , "    return (int64_t)path_length;"
        , "}"
        , ""
        , "int64_t tersus_fileLoad(void) {"
        , "    path_buffer[path_length] = 0;"
        , "    path_length = 0;"
        , "    free(loaded_file);"
        , "    loaded_file = NULL;"
        , "    loaded_length = 0;"
        , "    if (path_buffer[0] == 0) return -1;"
        , "    FILE *file = fopen((const char *)path_buffer, \"rb\");"
        , "    if (file == NULL) return -1;"
        , "    size_t capacity = 4096, length = 0;"
        , "    unsigned char *contents = malloc(capacity);"
        , "    if (contents == NULL) { fclose(file); return -1; }"
        , "    for (;;) {"
        , "        if (length == capacity) {"
        , "            capacity *= 2;"
        , "            unsigned char *grown = realloc(contents, capacity);"
        , "            if (grown == NULL) { free(contents); fclose(file); return -1; }"
        , "            contents = grown;"
        , "        }"
        , "        size_t got = fread(contents + length, 1, capacity - length, file);"
        , "        length += got;"
        , "        if (got == 0) break;"
        , "    }"
        , "    int failed = ferror(file);"
        , "    fclose(file);"
        , "    if (failed) { free(contents); return -1; }"
        , "    loaded_file = contents;"
        , "    loaded_length = length;"
        , "    return (int64_t)length;"
        , "}"
        , ""
        , "int64_t tersus_fileByte(int64_t index) {"
        , "    if (index < 0 || (uint64_t)index >= loaded_length) return -1;"
        , "    return (int64_t)loaded_file[index];"
        , "}"
        , ""
        , "int64_t tersus_storeByte(int64_t byte) {"
        , "    if (stored_length == stored_capacity) {"
        , "        stored_capacity = stored_capacity == 0 ? 4096 : stored_capacity * 2;"
        , "        stored_file = realloc(stored_file, stored_capacity);"
        , "        if (stored_file == NULL) fail(\"Out of memory\");"
        , "    }"
        , "    stored_file[stored_length++] = (unsigned char)(byte & 255);"
        , "    return (int64_t)stored_length;"
        , "}"
        , ""
        , "int64_t tersus_fileStore(void) {"
        , "    path_buffer[path_length] = 0;"
        , "    path_length = 0;"
        , "    size_t length = stored_length;"
        , "    stored_length = 0;"
        , "    if (path_buffer[0] == 0) return -1;"
        , "    FILE *file = fopen((const char *)path_buffer, \"wb\");"
        , "    if (file == NULL) return -1;"
        , "    size_t put = length == 0 ? 0 : fwrite(stored_file, 1, length, file);"
        , "    int closed = fclose(file);"
        , "    return (put == length && closed == 0) ? 0 : -1;"
        , "}"
        , ""
        , "// Threads (lib/thread.tersus, MirThreads): spawn starts entry(job, slot) on a thread of its own, with the stack the program"
        , "// has (RLIMIT_STACK, or 8 MiB when that is unlimited), and gives the handle that join waits for."
        , "typedef struct Thread {"
        , "    pthread_t thread;"
        , "    int64_t (*entry)(int64_t, int64_t);"
        , "    int64_t job;"
        , "    int64_t slot;"
        , "} Thread;"
        , ""
        , "static void *thread_start(void *argument) {"
        , "    Thread *t = argument;"
        , "#if !defined(TERSUS_CHECK) && !defined(TERSUS_SYSTEM_MALLOC)"
        , "    own_heap = &thread_heap;"
        , "#endif"
        , "    t->entry(t->job, t->slot);"
        , "    free(loaded_file);"
        , "    free(stored_file);"
        , "    return NULL;"
        , "}"
        , ""
        , "static size_t thread_stack_bytes(void) {"
        , "    struct rlimit limit;"
        , "    if (getrlimit(RLIMIT_STACK, &limit) == 0 && limit.rlim_cur != RLIM_INFINITY && limit.rlim_cur > 0) return (size_t)limit.rlim_cur;"
        , "    return (size_t)8 << 20;"
        , "}"
        , ""
        , "int64_t tersus_thread_spawn(int64_t (*entry)(int64_t, int64_t), int64_t job, int64_t slot) {"
        , "    Thread *t = malloc(sizeof(Thread));"
        , "    if (t == NULL) fail(\"Out of memory\");"
        , "    t->entry = entry;"
        , "    t->job = job;"
        , "    t->slot = slot;"
        , "    if (!threads_started) threads_started = 1;"
        , "    pthread_attr_t attributes;"
        , "    if (pthread_attr_init(&attributes) != 0) fail(\"Could not start a thread\");"
        , "    pthread_attr_setstacksize(&attributes, thread_stack_bytes());"
        , "    int started = pthread_create(&t->thread, &attributes, thread_start, t);"
        , "    pthread_attr_destroy(&attributes);"
        , "    if (started != 0) fail(\"Could not start a thread\");"
        , "    return (int64_t)(uintptr_t)t;"
        , "}"
        , ""
        , "int64_t tersus_thread_join(int64_t handle) {"
        , "    Thread *t = (Thread *)(uintptr_t)handle;"
        , "    if (pthread_join(t->thread, NULL) != 0) fail(\"Could not join a thread\");"
        , "    free(t);"
        , "    return 0;"
        , "}"
        , ""
        , "// readByte(): the next byte of the standard input, or -1 when there is no more"
        , "int64_t tersus_readByte(void) {"
        , "    int c = getchar();"
        , "    return c == EOF ? -1 : (int64_t)c;"
        , "}"
        , ""
        , "// Room for a value of the given number of bytes on the heap, which the caller fills in"
        , "unsigned char *tersus_box_new(int64_t bytes) {"
        , "    if (bytes > (int64_t)(SIZE_MAX / 2)) fail(\"Out of memory\");"
        , "    return allocate(bytes < 1 ? 1 : (size_t)bytes);"
        , "}"
        , ""
        , "// Addresses (POINTERS.md): the memory of Addr::alloc and Addr::resize, of so many slots of so many bytes, and an address as the number it is."
        , "// What is in the slots is the program's: the validator has proved that it is written before it is read and empty when it is freed."
        , "static size_t slot_bytes(int64_t count, int64_t bytes) {"
        , "    if (count < 0 || bytes < 0 || (bytes > 0 && count > (int64_t)(SIZE_MAX / 2) / bytes)) fail(\"Out of memory\");"
        , "    size_t size = (size_t)count * (size_t)bytes;"
        , "    return size < 1 ? 1 : size;"
        , "}"
        , ""
        , "int64_t tersus_addr_alloc(int64_t count, int64_t bytes) {"
        , "    return (int64_t)(uintptr_t)allocate(slot_bytes(count, bytes));"
        , "}"
        , ""
        , "int64_t tersus_addr_resize(int64_t address, int64_t count, int64_t bytes) {"
        , "    return (int64_t)(uintptr_t)reallocate((void *)(uintptr_t)address, slot_bytes(count, bytes));"
        , "}"
        , ""
        , "void tersus_addr_free(int64_t address) {"
        , "    release((void *)(uintptr_t)address);"
        , "}"
        , ""
        , "// Frees room on the heap, without what was in it (which has been moved out: a Box of the library that is cast)"
        , "void tersus_box_free(unsigned char *block) {"
        , "    release(block);"
        , "}"
        , ""
        ]
