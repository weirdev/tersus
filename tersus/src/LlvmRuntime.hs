module LlvmRuntime
    ( runtimeSource
    ) where

-- The C runtime that the emitted LLVM IR calls: what the program does that is not an instruction. `tersus build` writes
-- it to a temporary file beside the IR and compiles both with clang.
--
-- A value is held in words of 64 bits. An Int, a Bool (0 or 1), the address of a function, and the address of a list or of a box are
-- one word; the last two are the values of the heap, which have one owner (see MirOwnership), so they are freed with what is in
-- them, `push` and `set` change the list they are given, and a copy shares nothing with the original. A list is
-- `{ rc, len, cap, elements }` (`rc` is not used), the elements stride words apart, and a box is the words of what it holds. A
-- struct, an enum and an array are not on the heap but their words, held in the frame of a function, in a field, in a list or in a
-- box: a struct its fields' words, an enum a word that says the variant and then the fields of that variant, an array its elements.
-- The runtime prints, compares, copies and frees values by the descriptor of their type, which the emitted code defines as a
-- constant: its kind and what it is made of (the elements of a list, a box or an array, the variants of a struct or enum with their
-- field names and the descriptors of the fields).
runtimeSource :: String
runtimeSource =
    unlines
        [ "#include <stdint.h>"
        , "#include <stdio.h>"
        , "#include <stdlib.h>"
        , "#include <string.h>"
        , "#include <unistd.h>"
        , ""
        , "enum { KIND_INT = 0, KIND_BOOL = 1, KIND_LIST = 2, KIND_DATA = 3, KIND_FUNCTION = 4, KIND_ARRAY = 5, KIND_BOX = 6, KIND_FATBOX = 7 };"
        , ""
        , "typedef struct Type {"
        , "    int64_t kind;"
        , "    const void *aux; // a list: the Type of its elements. A box: the Type of what it holds. A fat box: the Type of the elements. A struct or enum: its Variants. An array: its ArrayInfo"
        , "} Type;"
        , ""
        , "// An array held inline: its elements, one after another (an element that is an array, a struct or an enum is its words, in line)"
        , "typedef struct ArrayInfo {"
        , "    int64_t count;"
        , "    const Type *element;"
        , "} ArrayInfo;"
        , ""
        , "typedef struct Field {"
        , "    const char *name;"
        , "    const Type *type;"
        , "} Field;"
        , ""
        , "typedef struct Variant {"
        , "    const char *name; // Enum::Variant, or the name of a struct"
        , "    int64_t count;"
        , "    const Field *fields;"
        , "} Variant;"
        , ""
        , "// The variants of a struct (one) or an enum. A value held inline is its fields' words, and an enum value starts with a word that"
        , "// says which variant it is (the position in the enum): tagged is 1 for an enum and 0 for a struct, which has no tag."
        , "typedef struct Variants {"
        , "    int64_t count;"
        , "    const Variant *variants;"
        , "    int64_t tagged;"
        , "} Variants;"
        , ""
        , "typedef struct List {"
        , "    int64_t rc;"
        , "    int64_t len;"
        , "    int64_t cap;"
        , "    uint64_t elements[];"
        , "} List;"
        , ""
        , "static void fail(const char *message);"
        , ""
        , "// The values of the heap come from here. Compiled with -DTERSUS_CHECK, every block is recorded and a block that is freed"
        , "// is filled with 0xDD and kept (so that a use of it reads that), a block freed twice is reported, and so is a block"
        , "// that is still there when the program ends. The tests build that way."
        , "#ifdef TERSUS_CHECK"
        , "typedef struct Block {"
        , "    uint64_t state;"
        , "    uint64_t size;"
        , "} Block;"
        , ""
        , "#define BLOCK_LIVE 0x11fe11fe11fe11feULL"
        , "#define BLOCK_FREED 0xdeaddeaddeaddeadULL"
        , ""
        , "static int64_t live_blocks = 0;"
        , "static int stopped = 0;"
        , ""
        , "static void check_failed(const char *message) {"
        , "    fprintf(stderr, \"Memory check failed: %s\\n\", message);"
        , "    _exit(99);"
        , "}"
        , ""
        , "static void check_leaks(void) {"
        , "    if (!stopped && live_blocks != 0) {"
        , "        fprintf(stderr, \"Memory check failed: %lld values were not freed\\n\", (long long)live_blocks);"
        , "        _exit(99);"
        , "    }"
        , "}"
        , ""
        , "__attribute__((constructor)) static void start_checking(void) {"
        , "    atexit(check_leaks);"
        , "}"
        , ""
        , "static void *allocate(size_t size) {"
        , "    Block *block = malloc(sizeof(Block) + size);"
        , "    if (block == NULL) fail(\"Out of memory\");"
        , "    block->state = BLOCK_LIVE;"
        , "    block->size = size;"
        , "    live_blocks++;"
        , "    return block + 1;"
        , "}"
        , ""
        , "static void release(void *memory) {"
        , "    Block *block = (Block *)memory - 1;"
        , "    if (block->state != BLOCK_LIVE) check_failed(\"a value is freed twice, or what is freed is not a value\");"
        , "    block->state = BLOCK_FREED;"
        , "    memset(memory, 0xDD, (size_t)block->size);"
        , "    live_blocks--;"
        , "}"
        , ""
        , "static void *reallocate(void *memory, size_t size) {"
        , "    Block *block = (Block *)memory - 1;"
        , "    if (block->state != BLOCK_LIVE) check_failed(\"a value that was freed is grown\");"
        , "    void *grown = allocate(size);"
        , "    memcpy(grown, memory, block->size < size ? (size_t)block->size : size);"
        , "    release(memory);"
        , "    return grown;"
        , "}"
        , "#else"
        , "static void *allocate(size_t size) {"
        , "    void *memory = malloc(size);"
        , "    if (memory == NULL) fail(\"Out of memory\");"
        , "    return memory;"
        , "}"
        , ""
        , "static void release(void *memory) {"
        , "    free(memory);"
        , "}"
        , ""
        , "static void *reallocate(void *memory, size_t size) {"
        , "    void *grown = realloc(memory, size);"
        , "    if (grown == NULL) fail(\"Out of memory\");"
        , "    return grown;"
        , "}"
        , "#endif"
        , ""
        , "static void fail(const char *message) {"
        , "    fprintf(stderr, \"Evaluation failed: %s\\n\", message);"
        , "#ifdef TERSUS_CHECK"
        , "    stopped = 1;"
        , "#endif"
        , "    exit(1);"
        , "}"
        , ""
        , "// An Int left its 64 bits: the same message and exit status as `tersus run`"
        , "void tersus_overflow(void) {"
        , "    fail(\"Integer overflow\");"
        , "}"
        , ""
        , "// Values are held in slots of words. A number, a Bool, the address of a function, and the address of a list or of a box (a value of"
        , "// the heap, which has one owner) are one word. A struct, an enum and an array are their words, in line, wherever they are held:"
        , "// the fields of a struct one after another, an enum a word that says the variant and then the fields of that variant (the room"
        , "// of the widest), an array its elements. A slot is dropped, copied, compared and printed by the descriptor of its type."
        , ""
        , "// The words of a value held inline"
        , "static int64_t words(const Type *type);"
        , ""
        , "static int64_t variant_words(const Variant *variant) {"
        , "    int64_t total = 0;"
        , "    for (int64_t i = 0; i < variant->count; i++) total += words(variant->fields[i].type);"
        , "    return total;"
        , "}"
        , ""
        , "static int64_t words(const Type *type) {"
        , "    if (type->kind == KIND_ARRAY) {"
        , "        const ArrayInfo *info = type->aux;"
        , "        return info->count * words(info->element);"
        , "    }"
        , "    if (type->kind == KIND_FATBOX) return 2;"
        , "    if (type->kind == KIND_DATA) {"
        , "        const Variants *vs = type->aux;"
        , "        int64_t widest = 0;"
        , "        for (int64_t i = 0; i < vs->count; i++) {"
        , "            int64_t w = variant_words(&vs->variants[i]);"
        , "            if (w > widest) widest = w;"
        , "        }"
        , "        return widest + (vs->tagged ? 1 : 0);"
        , "    }"
        , "    return 1;"
        , "}"
        , ""
        , "// What a slot holds, as the word that describes it: a number or the address of a value of the heap as it is, and for a value held"
        , "// inline the address of its words"
        , "static uint64_t slot_value(const Type *type, const uint64_t *slot) {"
        , "    return (type->kind == KIND_ARRAY || type->kind == KIND_DATA || type->kind == KIND_FATBOX) ? (uint64_t)slot : *slot;"
        , "}"
        , ""
        , "// The variant that a value held inline is, and where its fields start"
        , "static const Variant *variant_of(const Type *type, const uint64_t *slot) {"
        , "    const Variants *vs = type->aux;"
        , "    return &vs->variants[vs->tagged ? (int64_t)slot[0] : 0];"
        , "}"
        , ""
        , "static const uint64_t *fields_of(const Type *type, const uint64_t *slot) {"
        , "    return slot + (((const Variants *)type->aux)->tagged ? 1 : 0);"
        , "}"
        , ""
        , "// Whether a value of the type owns something to free: a list or a box, or a struct, an enum or an array that holds one"
        , "static int needs_drop(const Type *type) {"
        , "    switch (type->kind) {"
        , "    case KIND_LIST:"
        , "    case KIND_BOX:"
        , "    case KIND_FATBOX:"
        , "        return 1;"
        , "    case KIND_ARRAY:"
        , "        return needs_drop(((const ArrayInfo *)type->aux)->element);"
        , "    case KIND_DATA: {"
        , "        const Variants *vs = type->aux;"
        , "        for (int64_t i = 0; i < vs->count; i++) {"
        , "            for (int64_t j = 0; j < vs->variants[i].count; j++) {"
        , "                if (needs_drop(vs->variants[i].fields[j].type)) return 1;"
        , "            }"
        , "        }"
        , "        return 0;"
        , "    }"
        , "    default:"
        , "        return 0;"
        , "    }"
        , "}"
        , ""
        , "// A list of len elements of stride words each, which the caller fills in"
        , "List *tersus_list_new_words(int64_t len, int64_t stride) {"
        , "    size_t count = (size_t)len * (size_t)stride;"
        , "    List *list = allocate(sizeof(List) + count * sizeof(uint64_t));"
        , "    list->rc = 1;"
        , "    list->len = len;"
        , "    list->cap = len;"
        , "    memset(list->elements, 0, count * sizeof(uint64_t));"
        , "    return list;"
        , "}"
        , ""
        , "List *tersus_list_new(int64_t len) {"
        , "    return tersus_list_new_words(len, 1);"
        , "}"
        , ""
        , "// Room for a value of the given number of words on the heap, which the caller fills in"
        , "uint64_t *tersus_box_new(int64_t count) {"
        , "    if (count > (int64_t)(SIZE_MAX / sizeof(uint64_t) / 2)) fail(\"Out of memory\");"
        , "    return allocate((count < 1 ? 1 : (size_t)count) * sizeof(uint64_t));"
        , "}"
        , ""
        , "// Frees the room of a box, without what was in it (which has been moved out)"
        , "void tersus_box_free(uint64_t *block) {"
        , "    release(block);"
        , "}"
        , ""
        , "// Frees what the value in the slot owns, and leaves a list or a box it held holding nothing: a value that is not there (it was"
        , "// moved out, and the words are 0) is nothing to free"
        , "void tersus_drop(const Type *type, uint64_t *slot) {"
        , "    switch (type->kind) {"
        , "    case KIND_LIST: {"
        , "        List *list = (List *)*slot;"
        , "        if (list == NULL) return;"
        , "        const Type *element = type->aux;"
        , "        if (needs_drop(element)) {"
        , "            int64_t stride = words(element);"
        , "            for (int64_t i = 0; i < list->len; i++) tersus_drop(element, list->elements + i * stride);"
        , "        }"
        , "        release(list);"
        , "        *slot = 0;"
        , "        break;"
        , "    }"
        , "    case KIND_BOX: {"
        , "        uint64_t *block = (uint64_t *)*slot;"
        , "        if (block == NULL) return;"
        , "        tersus_drop(type->aux, block);"
        , "        release(block);"
        , "        *slot = 0;"
        , "        break;"
        , "    }"
        , "    case KIND_FATBOX: {"
        , "        uint64_t *block = (uint64_t *)slot[0];"
        , "        if (block == NULL) return;"
        , "        const Type *element = type->aux;"
        , "        if (needs_drop(element)) {"
        , "            int64_t step = words(element);"
        , "            for (int64_t i = 0; i < (int64_t)slot[1]; i++) tersus_drop(element, block + i * step);"
        , "        }"
        , "        release(block);"
        , "        slot[0] = 0;"
        , "        slot[1] = 0;"
        , "        break;"
        , "    }"
        , "    case KIND_ARRAY: {"
        , "        const ArrayInfo *info = type->aux;"
        , "        if (needs_drop(info->element)) {"
        , "            int64_t step = words(info->element);"
        , "            for (int64_t i = 0; i < info->count; i++) tersus_drop(info->element, slot + i * step);"
        , "        }"
        , "        break;"
        , "    }"
        , "    case KIND_DATA: {"
        , "        if (!needs_drop(type)) return;"
        , "        const Variant *variant = variant_of(type, slot);"
        , "        uint64_t *fields = (uint64_t *)fields_of(type, slot);"
        , "        int64_t at = 0;"
        , "        for (int64_t i = 0; i < variant->count; i++) {"
        , "            const Type *field = variant->fields[i].type;"
        , "            tersus_drop(field, fields + at);"
        , "            at += words(field);"
        , "        }"
        , "        break;"
        , "    }"
        , "    default:"
        , "        break;"
        , "    }"
        , "}"
        , ""
        , "// Copies the value of a slot into another that shares nothing with it. A value that is not there (0) is copied as it is."
        , "void tersus_clone(const Type *type, uint64_t *to, const uint64_t *from) {"
        , "    switch (type->kind) {"
        , "    case KIND_LIST: {"
        , "        const List *list = (const List *)*from;"
        , "        if (list == NULL) {"
        , "            *to = 0;"
        , "            return;"
        , "        }"
        , "        const Type *element = type->aux;"
        , "        int64_t stride = words(element);"
        , "        List *copy = tersus_list_new_words(list->len, stride);"
        , "        for (int64_t i = 0; i < list->len; i++) tersus_clone(element, copy->elements + i * stride, list->elements + i * stride);"
        , "        *to = (uint64_t)copy;"
        , "        break;"
        , "    }"
        , "    case KIND_BOX: {"
        , "        const uint64_t *block = (const uint64_t *)*from;"
        , "        if (block == NULL) {"
        , "            *to = 0;"
        , "            return;"
        , "        }"
        , "        uint64_t *copy = tersus_box_new(words(type->aux));"
        , "        tersus_clone(type->aux, copy, block);"
        , "        *to = (uint64_t)copy;"
        , "        break;"
        , "    }"
        , "    case KIND_FATBOX: {"
        , "        const uint64_t *block = (const uint64_t *)from[0];"
        , "        if (block == NULL) {"
        , "            to[0] = 0;"
        , "            to[1] = 0;"
        , "            return;"
        , "        }"
        , "        const Type *element = type->aux;"
        , "        int64_t step = words(element);"
        , "        int64_t count = (int64_t)from[1];"
        , "        uint64_t *copy = tersus_box_new(count * step);"
        , "        memcpy(copy, block, (size_t)(count * step) * sizeof(uint64_t));"
        , "        if (needs_drop(element)) {"
        , "            for (int64_t i = 0; i < count; i++) tersus_clone(element, copy + i * step, block + i * step);"
        , "        }"
        , "        to[0] = (uint64_t)copy;"
        , "        to[1] = (uint64_t)count;"
        , "        break;"
        , "    }"
        , "    case KIND_ARRAY: {"
        , "        const ArrayInfo *info = type->aux;"
        , "        int64_t step = words(info->element);"
        , "        memcpy(to, from, (size_t)(info->count * step) * sizeof(uint64_t));"
        , "        if (needs_drop(info->element)) {"
        , "            for (int64_t i = 0; i < info->count; i++) tersus_clone(info->element, to + i * step, from + i * step);"
        , "        }"
        , "        break;"
        , "    }"
        , "    case KIND_DATA: {"
        , "        memcpy(to, from, (size_t)words(type) * sizeof(uint64_t));"
        , "        if (needs_drop(type)) {"
        , "            const Variant *variant = variant_of(type, from);"
        , "            const uint64_t *source = fields_of(type, from);"
        , "            uint64_t *target = (uint64_t *)fields_of(type, to);"
        , "            int64_t at = 0;"
        , "            for (int64_t i = 0; i < variant->count; i++) {"
        , "                const Type *field = variant->fields[i].type;"
        , "                tersus_clone(field, target + at, source + at);"
        , "                at += words(field);"
        , "            }"
        , "        }"
        , "        break;"
        , "    }"
        , "    default:"
        , "        *to = *from;"
        , "        break;"
        , "    }"
        , "}"
        , ""
        , "// Room for one more element of stride words, which grows by doubling, so a list that is built by pushing costs time in"
        , "// proportion to its length"
        , "static List *list_room(List *list, int64_t stride) {"
        , "    if (list->len == list->cap) {"
        , "        int64_t cap = list->cap < 4 ? 4 : list->cap * 2;"
        , "        list = reallocate(list, sizeof(List) + (size_t)cap * (size_t)stride * sizeof(uint64_t));"
        , "        list->cap = cap;"
        , "    }"
        , "    return list;"
        , "}"
        , ""
        , "// The list with the element added at the end. The list is the caller's to change"
        , "List *tersus_list_push(List *list, uint64_t element) {"
        , "    list = list_room(list, 1);"
        , "    list->elements[list->len++] = element;"
        , "    return list;"
        , "}"
        , ""
        , "// The same for an element of stride words, moved in from where it is"
        , "List *tersus_list_push_words(List *list, const uint64_t *element, int64_t stride) {"
        , "    list = list_room(list, stride);"
        , "    memcpy(list->elements + list->len * stride, element, (size_t)stride * sizeof(uint64_t));"
        , "    list->len++;"
        , "    return list;"
        , "}"
        , ""
        , "// The list with the element at the index replaced, which frees the one it held. The type is that of the elements."
        , "List *tersus_list_set(List *list, int64_t index, uint64_t element, const Type *type) {"
        , "    if (needs_drop(type)) tersus_drop(type, list->elements + index);"
        , "    list->elements[index] = element;"
        , "    return list;"
        , "}"
        , ""
        , "// The same for an element of several words, moved in from where it is"
        , "List *tersus_list_set_words(List *list, int64_t index, const uint64_t *element, const Type *type) {"
        , "    int64_t stride = words(type);"
        , "    if (needs_drop(type)) tersus_drop(type, list->elements + index * stride);"
        , "    memcpy(list->elements + index * stride, element, (size_t)stride * sizeof(uint64_t));"
        , "    return list;"
        , "}"
        , ""
        , "// Equality is structural"
        , "int tersus_equal(const Type *type, uint64_t a, uint64_t b) {"
        , "    switch (type->kind) {"
        , "    case KIND_LIST: {"
        , "        const List *x = (const List *)a;"
        , "        const List *y = (const List *)b;"
        , "        if (x->len != y->len) return 0;"
        , "        const Type *element = type->aux;"
        , "        int64_t stride = words(element);"
        , "        for (int64_t i = 0; i < x->len; i++) {"
        , "            if (!tersus_equal(element, slot_value(element, x->elements + i * stride), slot_value(element, y->elements + i * stride))) return 0;"
        , "        }"
        , "        return 1;"
        , "    }"
        , "    case KIND_BOX: {"
        , "        const Type *held = type->aux;"
        , "        return tersus_equal(held, slot_value(held, (const uint64_t *)a), slot_value(held, (const uint64_t *)b));"
        , "    }"
        , "    case KIND_FATBOX: {"
        , "        const uint64_t *x = (const uint64_t *)a;"
        , "        const uint64_t *y = (const uint64_t *)b;"
        , "        if (x[1] != y[1]) return 0;"
        , "        const Type *element = type->aux;"
        , "        int64_t step = words(element);"
        , "        for (int64_t i = 0; i < (int64_t)x[1]; i++) {"
        , "            if (!tersus_equal(element, slot_value(element, (const uint64_t *)x[0] + i * step), slot_value(element, (const uint64_t *)y[0] + i * step))) return 0;"
        , "        }"
        , "        return 1;"
        , "    }"
        , "    case KIND_ARRAY: {"
        , "        const ArrayInfo *info = type->aux;"
        , "        const uint64_t *x = (const uint64_t *)a;"
        , "        const uint64_t *y = (const uint64_t *)b;"
        , "        int64_t step = words(info->element);"
        , "        for (int64_t i = 0; i < info->count; i++) {"
        , "            if (!tersus_equal(info->element, slot_value(info->element, x + i * step), slot_value(info->element, y + i * step))) return 0;"
        , "        }"
        , "        return 1;"
        , "    }"
        , "    case KIND_DATA: {"
        , "        const uint64_t *x = (const uint64_t *)a;"
        , "        const uint64_t *y = (const uint64_t *)b;"
        , "        const Variants *vs = type->aux;"
        , "        if (vs->tagged && x[0] != y[0]) return 0;"
        , "        const Variant *variant = variant_of(type, x);"
        , "        const uint64_t *xs = fields_of(type, x);"
        , "        const uint64_t *ys = fields_of(type, y);"
        , "        int64_t at = 0;"
        , "        for (int64_t i = 0; i < variant->count; i++) {"
        , "            const Type *field = variant->fields[i].type;"
        , "            if (!tersus_equal(field, slot_value(field, xs + at), slot_value(field, ys + at))) return 0;"
        , "            at += words(field);"
        , "        }"
        , "        return 1;"
        , "    }"
        , "    default:"
        , "        return a == b;"
        , "    }"
        , "}"
        , ""
        , "static void print_word(const Type *type, uint64_t word) {"
        , "    switch (type->kind) {"
        , "    case KIND_INT:"
        , "        printf(\"%lld\", (long long)(int64_t)word);"
        , "        break;"
        , "    case KIND_BOOL:"
        , "        fputs(word ? \"true\" : \"false\", stdout);"
        , "        break;"
        , "    case KIND_LIST: {"
        , "        const List *list = (const List *)word;"
        , "        const Type *element = type->aux;"
        , "        int64_t stride = words(element);"
        , "        putchar('[');"
        , "        for (int64_t i = 0; i < list->len; i++) {"
        , "            if (i > 0) fputs(\", \", stdout);"
        , "            print_word(element, slot_value(element, list->elements + i * stride));"
        , "        }"
        , "        putchar(']');"
        , "        break;"
        , "    }"
        , "    case KIND_BOX: {"
        , "        const Type *held = type->aux;"
        , "        print_word(held, slot_value(held, (const uint64_t *)word));"
        , "        break;"
        , "    }"
