module LlvmRuntime
    ( runtimeSource
    ) where

-- The C runtime that the emitted LLVM IR calls: what the program does that is not an instruction. `tersus build` writes
-- it to a temporary file beside the IR and compiles both with clang.
--
-- A value is held as C holds it (Mir.layoutOf): an Int, the address of a function and an address are 8 bytes, a Bool and a Byte 1, a
-- fixed-width integer its bits over 8. A struct, an enum and an array are their bytes, held in the frame of a function, in a field or in
-- memory at an address: a struct its fields at the offsets of C, an enum a U32 that says the variant and then the fields of that variant,
-- an array its elements. What is on the heap is memory at an address, which only a struct of the library or of the program holds: a list
-- is the struct List of lib/lists.tersus, and a Box the struct Box of lib/box.tersus (or a List, for a Box of an array), and each
-- is freed by its drop.
-- The runtime prints, copies and frees values by the descriptor of their type, which the emitted code defines as a
-- constant: its kind and what it is made of (the elements of an array, the variants of a struct or enum with their field names and the
-- descriptors of the fields, and its drop).
runtimeSource :: String
runtimeSource =
    unlines
        [ "#include <stdint.h>"
        , "#include <stdio.h>"
        , "#include <stdlib.h>"
        , "#include <string.h>"
        , "#include <unistd.h>"
        , ""
        , "enum { KIND_INT = 0, KIND_BOOL = 1, KIND_DATA = 3, KIND_FUNCTION = 4, KIND_ARRAY = 5, KIND_UNSIGNED = 8, KIND_SIGNED = 9 };"
        , ""
        , "typedef struct Type {"
        , "    int64_t kind;"
        , "    const void *aux; // an address: the Type of what it is the address of. A struct or enum: its Variants. An array: its ArrayInfo"
        , "    int64_t size; // the bytes of a value held inline, worked out when the program was made (walking the type for them at each drop and copy was most of the time of a program)"
        , "    int64_t drops; // 1 when a value owns something to free: a struct or an enum with a drop, or one or an array that holds one"
        , "} Type;"
        , ""
        , "// An array held inline: its elements, one after another (an element that is an array, a struct or an enum is its words, in line)"
        , "typedef struct ArrayInfo {"
        , "    int64_t count;"
        , "    const Type *element;"
        , "} ArrayInfo;"
        , ""
        , "typedef struct Field {"
        , "    const char *name;"
        , "    const Type *type;"
        , "    int64_t offset; // where the field is, in bytes from the start of the value"
        , "} Field;"
        , ""
        , "typedef struct Variant {"
        , "    const char *name; // Enum::Variant, or the name of a struct"
        , "    int64_t count;"
        , "    const Field *fields;"
        , "} Variant;"
        , ""
        , "// The variants of a struct (one) or an enum. A value held inline is its fields' words, and an enum value starts with a word that"
        , "// says which variant it is (the position in the enum): tagged is 1 for an enum and 0 for a struct, which has no tag. It is 2 for the struct that"
        , "// a list is made of (List in lib/lists.tersus: the elements at an address, and how many are in use), which is printed"
        , "// as a list; it is a struct otherwise. It is 3 for the struct that a Box is made of (Box in lib/box.tersus: the address of one value),"
        , "// which is printed and copied as the value at its address, and freed by its drop."
        , "typedef struct Variants {"
        , "    int64_t count;"
        , "    const Variant *variants;"
        , "    int64_t tagged;"
        , "} Variants;"
        , ""
        , "static void fail(const char *message);"
        , ""
        , "// The values of the heap come from here. Compiled with -DTERSUS_CHECK, every block is recorded and a block that is freed"
        , "// is filled with 0xDD and kept (so that a use of it reads that), a block freed twice is reported, and so is a block"
        , "// that is still there when the program ends. The tests build that way."
        , "#ifdef TERSUS_CHECK"
        , "typedef struct Block {"
        , "    uint64_t state;"
        , "    uint64_t size;"
        , "} Block;"
        , ""
        , "#define BLOCK_LIVE 0x11fe11fe11fe11feULL"
        , "#define BLOCK_FREED 0xdeaddeaddeaddeadULL"
        , ""
        , "static int64_t live_blocks = 0;"
        , "static int stopped = 0;"
        , ""
        , "static void check_failed(const char *message) {"
        , "    fprintf(stderr, \"Memory check failed: %s\\n\", message);"
        , "    _exit(99);"
        , "}"
        , ""
        , "static void check_leaks(void) {"
        , "    if (!stopped && live_blocks != 0) {"
        , "        fprintf(stderr, \"Memory check failed: %lld values were not freed\\n\", (long long)live_blocks);"
        , "        _exit(99);"
        , "    }"
        , "}"
        , ""
        , "__attribute__((constructor)) static void start_checking(void) {"
        , "    atexit(check_leaks);"
        , "}"
        , ""
        , "static void *allocate(size_t size) {"
        , "    Block *block = malloc(sizeof(Block) + size);"
        , "    if (block == NULL) fail(\"Out of memory\");"
        , "    block->state = BLOCK_LIVE;"
        , "    block->size = size;"
        , "    live_blocks++;"
        , "    return block + 1;"
        , "}"
        , ""
        , "static void release(void *memory) {"
        , "    Block *block = (Block *)memory - 1;"
        , "    if (block->state != BLOCK_LIVE) check_failed(\"a value is freed twice, or what is freed is not a value\");"
        , "    block->state = BLOCK_FREED;"
        , "    memset(memory, 0xDD, (size_t)block->size);"
        , "    live_blocks--;"
        , "}"
        , ""
        , "static void *reallocate(void *memory, size_t size) {"
        , "    Block *block = (Block *)memory - 1;"
        , "    if (block->state != BLOCK_LIVE) check_failed(\"a value that was freed is grown\");"
        , "    void *grown = allocate(size);"
        , "    memcpy(grown, memory, block->size < size ? (size_t)block->size : size);"
        , "    release(memory);"
        , "    return grown;"
        , "}"
        , "#else"
        , "static void *allocate(size_t size) {"
        , "    void *memory = malloc(size);"
        , "    if (memory == NULL) fail(\"Out of memory\");"
        , "    return memory;"
        , "}"
        , ""
        , "static void release(void *memory) {"
        , "    free(memory);"
        , "}"
        , ""
        , "static void *reallocate(void *memory, size_t size) {"
        , "    void *grown = realloc(memory, size);"
        , "    if (grown == NULL) fail(\"Out of memory\");"
        , "    return grown;"
        , "}"
        , "#endif"
        , ""
        , "static void fail(const char *message) {"
        , "    fprintf(stderr, \"Evaluation failed: %s\\n\", message);"
        , "#ifdef TERSUS_CHECK"
        , "    stopped = 1;"
        , "#endif"
        , "    exit(1);"
        , "}"
        , ""
        , "// An Int left its 64 bits: the same message and exit status as `tersus run`"
        , "void tersus_overflow(void) {"
        , "    fail(\"Integer overflow\");"
        , "}"
        , ""
        , "// writeByte(b): the byte b to the standard output, with what the program prints at the end. It is the value of the call."
        , "int64_t tersus_writeByte(int64_t byte) {"
        , "    putchar((int)(byte & 255));"
        , "    return byte;"
        , "}"
        , ""
        , "// writeError(b): the same for the standard error"
        , "int64_t tersus_writeError(int64_t byte) {"
        , "    fputc((int)(byte & 255), stderr);"
        , "    return byte;"
        , "}"
        , ""
        , "// The arguments of the program, which main gives to the runtime"
        , "static int program_argc = 0;"
        , "static char **program_argv = NULL;"
        , ""
        , "void tersus_init(int argc, char **argv) {"
        , "    program_argc = argc;"
        , "    program_argv = argv;"
        , "}"
        , ""
        , "// argCount(): the number of arguments, not counting the name of the program"
        , "int64_t tersus_argCount(void) {"
        , "    return program_argc > 0 ? (int64_t)program_argc - 1 : 0;"
        , "}"
        , ""
        , "// argByte(i, j): the byte j of argument i, or -1 when there is no such argument or byte"
        , "int64_t tersus_argByte(int64_t i, int64_t j) {"
        , "    if (i < 0 || i >= tersus_argCount() || j < 0) return -1;"
        , "    const char *argument = program_argv[i + 1];"
        , "    for (int64_t k = 0; k < j; k++) {"
        , "        if (argument[k] == 0) return -1;"
        , "    }"
        , "    return argument[j] == 0 ? -1 : (int64_t)(unsigned char)argument[j];"
        , "}"
        , ""
        , "// The files: a path is built a byte at a time, and then the file at it is loaded (and read a byte at a time) or a file that was built a byte at"
        , "// a time is stored there. A path is at most 4095 bytes, and ends at a byte that is 0."
        , "static unsigned char path_buffer[4096];"
        , "static size_t path_length = 0;"
        , "static unsigned char *loaded_file = NULL;"
        , "static size_t loaded_length = 0;"
        , "static unsigned char *stored_file = NULL;"
        , "static size_t stored_length = 0;"
        , "static size_t stored_capacity = 0;"
        , ""
        , "int64_t tersus_pathByte(int64_t byte) {"
        , "    if (path_length < 4095) path_buffer[path_length++] = (unsigned char)(byte & 255);"
        , "    return (int64_t)path_length;"
        , "}"
        , ""
        , "int64_t tersus_fileLoad(void) {"
        , "    path_buffer[path_length] = 0;"
        , "    path_length = 0;"
        , "    free(loaded_file);"
        , "    loaded_file = NULL;"
        , "    loaded_length = 0;"
        , "    if (path_buffer[0] == 0) return -1;"
        , "    FILE *file = fopen((const char *)path_buffer, \"rb\");"
        , "    if (file == NULL) return -1;"
        , "    size_t capacity = 4096, length = 0;"
        , "    unsigned char *contents = malloc(capacity);"
        , "    if (contents == NULL) { fclose(file); return -1; }"
        , "    for (;;) {"
        , "        if (length == capacity) {"
        , "            capacity *= 2;"
        , "            unsigned char *grown = realloc(contents, capacity);"
        , "            if (grown == NULL) { free(contents); fclose(file); return -1; }"
        , "            contents = grown;"
        , "        }"
        , "        size_t got = fread(contents + length, 1, capacity - length, file);"
        , "        length += got;"
        , "        if (got == 0) break;"
        , "    }"
        , "    int failed = ferror(file);"
        , "    fclose(file);"
        , "    if (failed) { free(contents); return -1; }"
        , "    loaded_file = contents;"
        , "    loaded_length = length;"
        , "    return (int64_t)length;"
        , "}"
        , ""
        , "int64_t tersus_fileByte(int64_t index) {"
        , "    if (index < 0 || (uint64_t)index >= loaded_length) return -1;"
        , "    return (int64_t)loaded_file[index];"
        , "}"
        , ""
        , "int64_t tersus_storeByte(int64_t byte) {"
        , "    if (stored_length == stored_capacity) {"
        , "        stored_capacity = stored_capacity == 0 ? 4096 : stored_capacity * 2;"
        , "        stored_file = realloc(stored_file, stored_capacity);"
        , "        if (stored_file == NULL) fail(\"Out of memory\");"
        , "    }"
        , "    stored_file[stored_length++] = (unsigned char)(byte & 255);"
        , "    return (int64_t)stored_length;"
        , "}"
        , ""
        , "int64_t tersus_fileStore(void) {"
        , "    path_buffer[path_length] = 0;"
        , "    path_length = 0;"
        , "    size_t length = stored_length;"
        , "    stored_length = 0;"
        , "    if (path_buffer[0] == 0) return -1;"
        , "    FILE *file = fopen((const char *)path_buffer, \"wb\");"
        , "    if (file == NULL) return -1;"
        , "    size_t put = length == 0 ? 0 : fwrite(stored_file, 1, length, file);"
        , "    int closed = fclose(file);"
        , "    return (put == length && closed == 0) ? 0 : -1;"
        , "}"
        , ""
        , "// readByte(): the next byte of the standard input, or -1 when there is no more"
        , "int64_t tersus_readByte(void) {"
        , "    int c = getchar();"
        , "    return c == EOF ? -1 : (int64_t)c;"
        , "}"
        , ""
        , "// Values are held in memory as C holds them (Mir.layoutOf, POINTERS.md Layout): an Int, the address of a function, and an"
        , "// address are 8 bytes, a Bool and a Byte 1, a fixed-width integer as many as it has bits over 8. A struct, an enum and an array are not on"
        , "// the heap but their bytes, in line, wherever they are held: a struct its fields, each at the offset its descriptor says (C's rules), an enum"
        , "// a U32 that says the variant and then the fields of that variant, an array its elements one after another. A slot is dropped, copied"
        , "// and printed by the descriptor of its type."
        , ""
        , "// The bytes of a value held inline"
        , "static int64_t size_of(const Type *type) {"
        , "    return type->size;"
        , "}"
        , ""
        , "static uint64_t read_word(const unsigned char *p) {"
        , "    uint64_t w;"
        , "    memcpy(&w, p, sizeof w);"
        , "    return w;"
        , "}"
        , ""
        , "static void write_word(unsigned char *p, uint64_t w) {"
        , "    memcpy(p, &w, sizeof w);"
        , "}"
        , ""
        , "// What a slot holds, as the word that describes it: a number (widened to 64 bits, with its sign for a signed one), a Bool as 0 or 1, the"
        , "// address of a value of the heap as it is, and for a value held inline the address of it"
        , "static uint64_t slot_value(const Type *type, const unsigned char *slot) {"
        , "    switch (type->kind) {"
        , "    case KIND_ARRAY:"
        , "    case KIND_DATA:"
        , "        return (uint64_t)(uintptr_t)slot;"
        , "    case KIND_BOOL:"
        , "        return slot[0] != 0;"
        , "    case KIND_UNSIGNED:"
        , "        if (type->size == 1) return slot[0];"
        , "        if (type->size == 2) { uint16_t v; memcpy(&v, slot, 2); return v; }"
        , "        if (type->size == 4) { uint32_t v; memcpy(&v, slot, 4); return v; }"
        , "        return read_word(slot);"
        , "    case KIND_SIGNED:"
        , "        if (type->size == 1) { int8_t v; memcpy(&v, slot, 1); return (uint64_t)(int64_t)v; }"
        , "        if (type->size == 2) { int16_t v; memcpy(&v, slot, 2); return (uint64_t)(int64_t)v; }"
        , "        if (type->size == 4) { int32_t v; memcpy(&v, slot, 4); return (uint64_t)(int64_t)v; }"
        , "        return read_word(slot);"
        , "    default:"
        , "        return read_word(slot);"
        , "    }"
        , "}"
        , ""
        , "// The variant that a value held inline is: an enum value starts with a U32 that says which (the position in the enum)"
        , "static const Variant *variant_of(const Type *type, const unsigned char *slot) {"
        , "    const Variants *vs = type->aux;"
        , "    uint32_t tag = 0;"
        , "    if (vs->tagged == 1) memcpy(&tag, slot, sizeof tag);"
        , "    return &vs->variants[vs->tagged == 1 ? (int64_t)tag : 0];"
        , "}"
        , ""
        , "// A list of the library: its elements are the first len of the array (at the address that is the first field), where len is the"
        , "// second field, and the room that is left is not part of it"
        , "static int is_list_like(const Type *type) {"
        , "    return type->kind == KIND_DATA && ((const Variants *)type->aux)->tagged == 2;"
        , "}"
        , ""
        , "static const Type *list_like_element(const Type *type) {"
        , "    return ((const Variants *)type->aux)->variants[0].fields[0].type->aux;"
        , "}"
        , ""
        , "static const unsigned char *list_like_elements(const Type *type, const unsigned char *value) {"
        , "    return (const unsigned char *)(uintptr_t)read_word(value + ((const Variants *)type->aux)->variants[0].fields[0].offset);"
        , "}"
        , ""
        , "static int64_t list_like_capacity_offset(const Type *type) {"
        , "    return ((const Variants *)type->aux)->variants[0].fields[2].offset;"
        , "}"
        , ""
        , "static int64_t list_like_length(const Type *type, const unsigned char *value) {"
        , "    return (int64_t)read_word(value + ((const Variants *)type->aux)->variants[0].fields[1].offset);"
        , "}"
        , ""
        , "// A Box of the library: the value at the address that is its first field"
        , "static int is_box_like(const Type *type) {"
        , "    return type->kind == KIND_DATA && ((const Variants *)type->aux)->tagged == 3;"
        , "}"
        , ""
        , "static const unsigned char *box_like_value(const Type *type, const unsigned char *value) {"
        , "    return (const unsigned char *)(uintptr_t)read_word(value + ((const Variants *)type->aux)->variants[0].fields[0].offset);"
        , "}"
        , ""
        , "// Whether a value of the type owns something to free: a struct or an enum with a drop, or one or an array that holds one"
        , "static int needs_drop(const Type *type) {"
        , "    return type->drops != 0;"
        , "}"
        , ""
        , "// Room for a value of the given number of bytes on the heap, which the caller fills in"
        , "unsigned char *tersus_box_new(int64_t bytes) {"
        , "    if (bytes > (int64_t)(SIZE_MAX / 2)) fail(\"Out of memory\");"
        , "    return allocate(bytes < 1 ? 1 : (size_t)bytes);"
        , "}"
        , ""
        , "// Addresses (POINTERS.md): the memory of Addr::alloc and Addr::resize, of so many slots of so many bytes, and an address as the number it is."
        , "// What is in the slots is the program's: the validator has proved that it is written before it is read and empty when it is freed."
        , "static size_t slot_bytes(int64_t count, int64_t bytes) {"
        , "    if (count < 0 || bytes < 0 || (bytes > 0 && count > (int64_t)(SIZE_MAX / 2) / bytes)) fail(\"Out of memory\");"
        , "    size_t size = (size_t)count * (size_t)bytes;"
        , "    return size < 1 ? 1 : size;"
        , "}"
        , ""
        , "int64_t tersus_addr_alloc(int64_t count, int64_t bytes) {"
        , "    return (int64_t)(uintptr_t)allocate(slot_bytes(count, bytes));"
        , "}"
        , ""
        , "int64_t tersus_addr_resize(int64_t address, int64_t count, int64_t bytes) {"
        , "    return (int64_t)(uintptr_t)reallocate((void *)(uintptr_t)address, slot_bytes(count, bytes));"
        , "}"
        , ""
        , "void tersus_addr_free(int64_t address) {"
        , "    release((void *)(uintptr_t)address);"
        , "}"
        , ""
        , "// Frees room on the heap, without what was in it (which has been moved out: a Box of the library that is cast)"
        , "void tersus_box_free(unsigned char *block) {"
        , "    release(block);"
        , "}"
        , ""
        , "// Copies the value of a slot into another that shares nothing with it. A value that is not there (0) is copied as it is."
        , "void tersus_clone(const Type *type, unsigned char *to, const unsigned char *from) {"
        , "    switch (type->kind) {"
        , "    case KIND_ARRAY: {"
        , "        const ArrayInfo *info = type->aux;"
        , "        int64_t step = size_of(info->element);"
        , "        if (info->count * step > 0) memcpy(to, from, (size_t)(info->count * step));"
        , "        if (needs_drop(info->element)) {"
        , "            for (int64_t i = 0; i < info->count; i++) tersus_clone(info->element, to + i * step, from + i * step);"
        , "        }"
        , "        break;"
        , "    }"
        , "    case KIND_DATA: {"
        , "        if (size_of(type) > 0) memcpy(to, from, (size_t)size_of(type));"
        , "        if (is_list_like(type)) {"
        , "            // (a copy of a list has memory of its own, with room for the elements in use, which are copied)"
        , "            const unsigned char *elements = list_like_elements(type, from);"
        , "            if (elements == NULL) return;"
        , "            const Type *element = list_like_element(type);"
        , "            int64_t step = size_of(element);"
        , "            int64_t count = list_like_length(type, from);"
        , "            unsigned char *copy = tersus_box_new(count * step);"
        , "            if (count * step > 0) memcpy(copy, elements, (size_t)(count * step));"
        , "            if (needs_drop(element)) {"
        , "                for (int64_t i = 0; i < count; i++) tersus_clone(element, copy + i * step, elements + i * step);"
        , "            }"
        , "            write_word(to + ((const Variants *)type->aux)->variants[0].fields[0].offset, (uint64_t)(uintptr_t)copy);"
        , "            write_word(to + list_like_capacity_offset(type), (uint64_t)count);"
        , "            return;"
        , "        }"
        , "        if (is_box_like(type)) {"
        , "            // (a copy of a Box has room of its own, with a copy of the value)"
        , "            const unsigned char *held = box_like_value(type, from);"
        , "            if (held == NULL) return;"
        , "            const Type *element = list_like_element(type);"
        , "            unsigned char *copy = tersus_box_new(size_of(element));"
        , "            tersus_clone(element, copy, held);"
        , "            write_word(to + ((const Variants *)type->aux)->variants[0].fields[0].offset, (uint64_t)(uintptr_t)copy);"
        , "            return;"
        , "        }"
        , "        if (needs_drop(type)) {"
        , "            const Variant *variant = variant_of(type, from);"
        , "            for (int64_t i = 0; i < variant->count; i++) {"
        , "                const Field *field = &variant->fields[i];"
        , "                tersus_clone(field->type, to + field->offset, from + field->offset);"
        , "            }"
        , "        }"
        , "        break;"
        , "    }"
        , "    default:"
        , "        if (size_of(type) > 0) memcpy(to, from, (size_t)size_of(type));"
        , "        break;"
        , "    }"
        , "}"
        , ""
        ]
