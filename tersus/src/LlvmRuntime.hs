module LlvmRuntime
    ( runtimeSource
    ) where

-- The C runtime that the emitted LLVM IR calls: what the program does that is not an instruction. `tersus build` writes
-- it to a temporary file beside the IR and compiles both with clang.
--
-- A value is a 64-bit word: an Int, a Bool (0 or 1), or an address: of a list, of a struct or enum value, or of a function.
-- A list is `{ rc, len, cap, elements }` and a struct or enum value `{ rc, tag, fields }` (the tag is the position of the
-- variant in the enum, 0 for a struct), and `rc` (a reference count) is not used yet: nothing is freed. The runtime prints
-- and compares values by the descriptor of their type, which the emitted code defines as a constant: its kind and what it
-- is made of (the descriptor of the elements of a list, the variants of a struct or enum with their field names and the
-- descriptors of the fields).
runtimeSource :: String
runtimeSource =
    unlines
        [ "#include <stdint.h>"
        , "#include <stdio.h>"
        , "#include <stdlib.h>"
        , "#include <string.h>"
        , ""
        , "enum { KIND_INT = 0, KIND_BOOL = 1, KIND_LIST = 2, KIND_DATA = 3, KIND_FUNCTION = 4 };"
        , ""
        , "typedef struct Type {"
        , "    int64_t kind;"
        , "    const void *aux; // a list: the Type of its elements. A struct or enum: its Variants"
        , "} Type;"
        , ""
        , "typedef struct Field {"
        , "    const char *name;"
        , "    const Type *type;"
        , "} Field;"
        , ""
        , "typedef struct Variant {"
        , "    const char *name; // Enum::Variant, or the name of a struct"
        , "    int64_t count;"
        , "    const Field *fields;"
        , "} Variant;"
        , ""
        , "typedef struct Variants {"
        , "    int64_t count;"
        , "    const Variant *variants;"
        , "} Variants;"
        , ""
        , "typedef struct Data {"
        , "    int64_t rc;"
        , "    int64_t tag;"
        , "    uint64_t fields[];"
        , "} Data;"
        , ""
        , "typedef struct List {"
        , "    int64_t rc;"
        , "    int64_t len;"
        , "    int64_t cap;"
        , "    uint64_t elements[];"
        , "} List;"
        , ""
        , "static void fail(const char *message) {"
        , "    fprintf(stderr, \"Evaluation failed: %s\\n\", message);"
        , "    exit(1);"
        , "}"
        , ""
        , "// An Int left its 64 bits: the same message and exit status as `tersus run`"
        , "void tersus_overflow(void) {"
        , "    fail(\"Integer overflow\");"
        , "}"
        , ""
        , "// A list of len elements, which the caller fills in"
        , "List *tersus_list_new(int64_t len) {"
        , "    List *list = malloc(sizeof(List) + (size_t)len * sizeof(uint64_t));"
        , "    if (list == NULL) fail(\"Out of memory\");"
        , "    list->rc = 1;"
        , "    list->len = len;"
        , "    list->cap = len;"
        , "    return list;"
        , "}"
        , ""
        , "// A struct or enum value of a variant with the number of fields, which the caller fills in"
        , "Data *tersus_data_new(int64_t tag, int64_t fields) {"
        , "    Data *data = malloc(sizeof(Data) + (size_t)fields * sizeof(uint64_t));"
        , "    if (data == NULL) fail(\"Out of memory\");"
        , "    data->rc = 1;"
        , "    data->tag = tag;"
        , "    return data;"
        , "}"
        , ""
        , "// The list with the element added at the end; a list is a value, so the argument is not changed"
        , "List *tersus_list_push(const List *list, uint64_t element) {"
        , "    List *result = tersus_list_new(list->len + 1);"
        , "    memcpy(result->elements, list->elements, (size_t)list->len * sizeof(uint64_t));"
        , "    result->elements[list->len] = element;"
        , "    return result;"
        , "}"
        , ""
        , "// The list with the element at the index replaced"
        , "List *tersus_list_set(const List *list, int64_t index, uint64_t element) {"
        , "    List *result = tersus_list_new(list->len);"
        , "    memcpy(result->elements, list->elements, (size_t)list->len * sizeof(uint64_t));"
        , "    result->elements[index] = element;"
        , "    return result;"
        , "}"
        , ""
        , "// Equality is structural"
        , "int tersus_equal(const Type *type, uint64_t a, uint64_t b) {"
        , "    if (type->kind == KIND_LIST) {"
        , "        const List *x = (const List *)a;"
        , "        const List *y = (const List *)b;"
        , "        if (x->len != y->len) return 0;"
        , "        for (int64_t i = 0; i < x->len; i++) {"
        , "            if (!tersus_equal((const Type *)type->aux, x->elements[i], y->elements[i])) return 0;"
        , "        }"
        , "        return 1;"
        , "    }"
        , "    if (type->kind == KIND_DATA) {"
        , "        const Data *x = (const Data *)a;"
        , "        const Data *y = (const Data *)b;"
        , "        if (x->tag != y->tag) return 0;"
        , "        const Variant *variant = &((const Variants *)type->aux)->variants[x->tag];"
        , "        for (int64_t i = 0; i < variant->count; i++) {"
        , "            if (!tersus_equal(variant->fields[i].type, x->fields[i], y->fields[i])) return 0;"
        , "        }"
        , "        return 1;"
        , "    }"
        , "    return a == b;"
        , "}"
        , ""
        , "static void print_word(const Type *type, uint64_t word) {"
        , "    switch (type->kind) {"
        , "    case KIND_INT:"
        , "        printf(\"%lld\", (long long)(int64_t)word);"
        , "        break;"
        , "    case KIND_BOOL:"
        , "        fputs(word ? \"true\" : \"false\", stdout);"
        , "        break;"
        , "    case KIND_LIST: {"
        , "        const List *list = (const List *)word;"
        , "        putchar('[');"
        , "        for (int64_t i = 0; i < list->len; i++) {"
        , "            if (i > 0) fputs(\", \", stdout);"
        , "            print_word((const Type *)type->aux, list->elements[i]);"
        , "        }"
        , "        putchar(']');"
        , "        break;"
        , "    }"
        , "    case KIND_DATA: {"
        , "        const Data *data = (const Data *)word;"
        , "        const Variant *variant = &((const Variants *)type->aux)->variants[data->tag];"
        , "        fputs(variant->name, stdout);"
        , "        if (variant->count > 0) {"
        , "            fputs(\" { \", stdout);"
        , "            for (int64_t i = 0; i < variant->count; i++) {"
        , "                if (i > 0) fputs(\", \", stdout);"
        , "                printf(\"%s: \", variant->fields[i].name);"
        , "                print_word(variant->fields[i].type, data->fields[i]);"
        , "            }"
        , "            fputs(\" }\", stdout);"
        , "        }"
        , "        break;"
        , "    }"
        , "    case KIND_FUNCTION:"
        , "        fputs(\"<function>\", stdout);"
        , "        break;"
        , "    }"
        , "}"
        , ""
        , "// The return value of the program, and a new line"
        , "void tersus_print(const Type *type, uint64_t word) {"
        , "    print_word(type, word);"
        , "    putchar('\\n');"
        , "}"
        ]
