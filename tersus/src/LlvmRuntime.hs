module LlvmRuntime
    ( runtimeSource
    ) where

-- The C runtime that the emitted LLVM IR calls: what the program does that is not an instruction. `tersus build` writes
-- it to a temporary file beside the IR and compiles both with clang.
--
-- A value is a 64-bit word: an Int, a Bool (0 or 1), or an address: of a list, of a struct or enum value, or of a function.
-- A list is `{ rc, len, cap, elements }` and a struct or enum value `{ rc, tag, fields }` (the tag is the position of the
-- variant in the enum, 0 for a struct); `rc` is not used. A value of the heap has one owner (see MirOwnership), so it is
-- freed with what is in it, `push` and `set` change the list they are given, and a copy shares nothing with the original. An
-- array is not a value of the heap but the words of its elements, held in the frame of a function, which the runtime only
-- compares and prints (by a descriptor of kind 5 with its count and the descriptor of its elements).
-- The runtime prints, compares, copies and frees values by the descriptor of their type, which the emitted code defines as a
-- constant: its kind and what it is made of (the descriptor of the elements of a list, the variants of a struct or enum with
-- their field names and the descriptors of the fields).
runtimeSource :: String
runtimeSource =
    unlines
        [ "#include <stdint.h>"
        , "#include <stdio.h>"
        , "#include <stdlib.h>"
        , "#include <string.h>"
        , "#include <unistd.h>"
        , ""
        , "enum { KIND_INT = 0, KIND_BOOL = 1, KIND_LIST = 2, KIND_DATA = 3, KIND_FUNCTION = 4, KIND_ARRAY = 5 };"
        , ""
        , "typedef struct Type {"
        , "    int64_t kind;"
        , "    const void *aux; // a list: the Type of its elements. A struct or enum: its Variants"
        , "} Type;"
        , ""
        , "// An array held inline: its elements, one word each (an element that is an array is its words, in line)"
        , "typedef struct ArrayInfo {"
        , "    int64_t count;"
        , "    const Type *element;"
        , "} ArrayInfo;"
        , ""
        , "typedef struct Field {"
        , "    const char *name;"
        , "    const Type *type;"
        , "} Field;"
        , ""
        , "typedef struct Variant {"
        , "    const char *name; // Enum::Variant, or the name of a struct"
        , "    int64_t count;"
        , "    const Field *fields;"
        , "} Variant;"
        , ""
        , "typedef struct Variants {"
        , "    int64_t count;"
        , "    const Variant *variants;"
        , "} Variants;"
        , ""
        , "typedef struct Data {"
        , "    int64_t rc;"
        , "    int64_t tag;"
        , "    uint64_t fields[];"
        , "} Data;"
        , ""
        , "typedef struct List {"
        , "    int64_t rc;"
        , "    int64_t len;"
        , "    int64_t cap;"
        , "    uint64_t elements[];"
        , "} List;"
        , ""
        , "static void fail(const char *message);"
        , ""
        , "// The values of the heap come from here. Compiled with -DTERSUS_CHECK, every block is recorded and a block that is freed"
        , "// is filled with 0xDD and kept (so that a use of it reads that), a block freed twice is reported, and so is a block"
        , "// that is still there when the program ends. The tests build that way."
        , "#ifdef TERSUS_CHECK"
        , "typedef struct Block {"
        , "    uint64_t state;"
        , "    uint64_t size;"
        , "} Block;"
        , ""
        , "#define BLOCK_LIVE 0x11fe11fe11fe11feULL"
        , "#define BLOCK_FREED 0xdeaddeaddeaddeadULL"
        , ""
        , "static int64_t live_blocks = 0;"
        , "static int stopped = 0;"
        , ""
        , "static void check_failed(const char *message) {"
        , "    fprintf(stderr, \"Memory check failed: %s\\n\", message);"
        , "    _exit(99);"
        , "}"
        , ""
        , "static void check_leaks(void) {"
        , "    if (!stopped && live_blocks != 0) {"
        , "        fprintf(stderr, \"Memory check failed: %lld values were not freed\\n\", (long long)live_blocks);"
        , "        _exit(99);"
        , "    }"
        , "}"
        , ""
        , "__attribute__((constructor)) static void start_checking(void) {"
        , "    atexit(check_leaks);"
        , "}"
        , ""
        , "static void *allocate(size_t size) {"
        , "    Block *block = malloc(sizeof(Block) + size);"
        , "    if (block == NULL) fail(\"Out of memory\");"
        , "    block->state = BLOCK_LIVE;"
        , "    block->size = size;"
        , "    live_blocks++;"
        , "    return block + 1;"
        , "}"
        , ""
        , "static void release(void *memory) {"
        , "    Block *block = (Block *)memory - 1;"
        , "    if (block->state != BLOCK_LIVE) check_failed(\"a value is freed twice, or what is freed is not a value\");"
        , "    block->state = BLOCK_FREED;"
        , "    memset(memory, 0xDD, (size_t)block->size);"
        , "    live_blocks--;"
        , "}"
        , ""
        , "static void *reallocate(void *memory, size_t size) {"
        , "    Block *block = (Block *)memory - 1;"
        , "    if (block->state != BLOCK_LIVE) check_failed(\"a value that was freed is grown\");"
        , "    void *grown = allocate(size);"
        , "    memcpy(grown, memory, block->size < size ? (size_t)block->size : size);"
        , "    release(memory);"
        , "    return grown;"
        , "}"
        , "#else"
        , "static void *allocate(size_t size) {"
        , "    void *memory = malloc(size);"
        , "    if (memory == NULL) fail(\"Out of memory\");"
        , "    return memory;"
        , "}"
        , ""
        , "static void release(void *memory) {"
        , "    free(memory);"
        , "}"
        , ""
        , "static void *reallocate(void *memory, size_t size) {"
        , "    void *grown = realloc(memory, size);"
        , "    if (grown == NULL) fail(\"Out of memory\");"
        , "    return grown;"
        , "}"
        , "#endif"
        , ""
        , "static void fail(const char *message) {"
        , "    fprintf(stderr, \"Evaluation failed: %s\\n\", message);"
        , "#ifdef TERSUS_CHECK"
        , "    stopped = 1;"
        , "#endif"
        , "    exit(1);"
        , "}"
        , ""
        , "// An Int left its 64 bits: the same message and exit status as `tersus run`"
        , "void tersus_overflow(void) {"
        , "    fail(\"Integer overflow\");"
        , "}"
        , ""
        , "// The words of a value held inline: an array is its elements', and anything else is one (a number, or the address of a value of"
        , "// the heap)"
        , "static int64_t words(const Type *type) {"
        , "    if (type->kind != KIND_ARRAY) return 1;"
        , "    const ArrayInfo *info = type->aux;"
        , "    return info->count * words(info->element);"
        , "}"
        , ""
        , "// What a slot holds, as the word that describes it: a number or the address of a value of the heap as it is, and for an array the"
        , "// address of its words"
        , "static uint64_t slot_value(const Type *type, const uint64_t *slot) {"
        , "    return type->kind == KIND_ARRAY ? (uint64_t)slot : *slot;"
        , "}"
        , ""
        , "// A list of len elements of stride words each, which the caller fills in"
        , "List *tersus_list_new_words(int64_t len, int64_t stride) {"
        , "    size_t count = (size_t)len * (size_t)stride;"
        , "    List *list = allocate(sizeof(List) + count * sizeof(uint64_t));"
        , "    list->rc = 1;"
        , "    list->len = len;"
        , "    list->cap = len;"
        , "    memset(list->elements, 0, count * sizeof(uint64_t));"
        , "    return list;"
        , "}"
        , ""
        , "List *tersus_list_new(int64_t len) {"
        , "    return tersus_list_new_words(len, 1);"
        , "}"
        , ""
        , "// A struct or enum value of a variant with the number of words its fields take, which the caller fills in"
        , "Data *tersus_data_new(int64_t tag, int64_t fields) {"
        , "    Data *data = allocate(sizeof(Data) + (size_t)fields * sizeof(uint64_t));"
        , "    data->rc = 1;"
        , "    data->tag = tag;"
        , "    memset(data->fields, 0, (size_t)fields * sizeof(uint64_t));"
        , "    return data;"
        , "}"
        , ""
        , "static int owns(const Type *type) {"
        , "    return type->kind == KIND_LIST || type->kind == KIND_DATA;"
        , "}"
        , ""
        , "// The words of the fields of a variant"
        , "static int64_t variant_words(const Variant *variant) {"
        , "    int64_t total = 0;"
        , "    for (int64_t i = 0; i < variant->count; i++) total += words(variant->fields[i].type);"
        , "    return total;"
        , "}"
        , ""
        , "// Frees a value and what is in it; a value that is not there (it was moved) is nothing to free"
        , "void tersus_drop(const Type *type, void *value) {"
        , "    if (value == NULL) return;"
        , "    if (type->kind == KIND_LIST) {"
        , "        List *list = value;"
        , "        const Type *element = type->aux;"
        , "        if (owns(element)) {"
        , "            for (int64_t i = 0; i < list->len; i++) tersus_drop(element, (void *)list->elements[i]);"
        , "        }"
        , "        release(list);"
        , "    } else if (type->kind == KIND_DATA) {"
        , "        Data *data = value;"
        , "        const Variant *variant = &((const Variants *)type->aux)->variants[data->tag];"
        , "        int64_t at = 0;"
        , "        for (int64_t i = 0; i < variant->count; i++) {"
        , "            const Type *field = variant->fields[i].type;"
        , "            if (owns(field)) tersus_drop(field, (void *)data->fields[at]);"
        , "            at += words(field);"
        , "        }"
        , "        release(data);"
        , "    }"
        , "}"
        , ""
        , "// Copies a slot into another: a value of the heap is cloned, and anything else (a number, or the words of an array) is copied"
        , "static void clone_slot(const Type *type, uint64_t *to, const uint64_t *from);"
        , ""
        , "// A copy that shares nothing with the value"
        , "void *tersus_clone(const Type *type, const void *value) {"
        , "    if (value == NULL) return NULL;"
        , "    if (type->kind == KIND_LIST) {"
        , "        const List *list = value;"
        , "        const Type *element = type->aux;"
        , "        int64_t stride = words(element);"
        , "        List *copy = tersus_list_new_words(list->len, stride);"
        , "        for (int64_t i = 0; i < list->len; i++) clone_slot(element, copy->elements + i * stride, list->elements + i * stride);"
        , "        return copy;"
        , "    }"
        , "    if (type->kind == KIND_DATA) {"
        , "        const Data *data = value;"
        , "        const Variant *variant = &((const Variants *)type->aux)->variants[data->tag];"
        , "        Data *copy = tersus_data_new(data->tag, variant_words(variant));"
        , "        int64_t at = 0;"
        , "        for (int64_t i = 0; i < variant->count; i++) {"
        , "            const Type *field = variant->fields[i].type;"
        , "            clone_slot(field, copy->fields + at, data->fields + at);"
        , "            at += words(field);"
        , "        }"
        , "        return copy;"
        , "    }"
        , "    return (void *)value;"
        , "}"
        , ""
        , "static void clone_slot(const Type *type, uint64_t *to, const uint64_t *from) {"
        , "    if (owns(type)) {"
        , "        *to = (uint64_t)tersus_clone(type, (const void *)*from);"
        , "    } else {"
        , "        memcpy(to, from, (size_t)words(type) * sizeof(uint64_t));"
        , "    }"
        , "}"
        , ""
        , "// Room for one more element of stride words, which grows by doubling, so a list that is built by pushing costs time in"
        , "// proportion to its length"
        , "static List *list_room(List *list, int64_t stride) {"
        , "    if (list->len == list->cap) {"
        , "        int64_t cap = list->cap < 4 ? 4 : list->cap * 2;"
        , "        list = reallocate(list, sizeof(List) + (size_t)cap * (size_t)stride * sizeof(uint64_t));"
        , "        list->cap = cap;"
        , "    }"
        , "    return list;"
        , "}"
        , ""
        , "// The list with the element added at the end. The list is the caller's to change"
        , "List *tersus_list_push(List *list, uint64_t element) {"
        , "    list = list_room(list, 1);"
        , "    list->elements[list->len++] = element;"
        , "    return list;"
        , "}"
        , ""
        , "// The same for an element of stride words (an array), copied from where it is"
        , "List *tersus_list_push_words(List *list, const uint64_t *element, int64_t stride) {"
        , "    list = list_room(list, stride);"
        , "    memcpy(list->elements + list->len * stride, element, (size_t)stride * sizeof(uint64_t));"
        , "    list->len++;"
        , "    return list;"
        , "}"
        , ""
        , "// The list with the element at the index replaced, which frees the one it held. The type is that of the elements."
        , "List *tersus_list_set(List *list, int64_t index, uint64_t element, const Type *type) {"
        , "    if (owns(type)) tersus_drop(type, (void *)list->elements[index]);"
        , "    list->elements[index] = element;"
        , "    return list;"
        , "}"
        , ""
        , "// The same for an element of stride words (an array, which holds nothing to free)"
        , "List *tersus_list_set_words(List *list, int64_t index, const uint64_t *element, int64_t stride) {"
        , "    memcpy(list->elements + index * stride, element, (size_t)stride * sizeof(uint64_t));"
        , "    return list;"
        , "}"
        , ""
        , "// Equality is structural"
        , "int tersus_equal(const Type *type, uint64_t a, uint64_t b) {"
        , "    if (type->kind == KIND_LIST) {"
        , "        const List *x = (const List *)a;"
        , "        const List *y = (const List *)b;"
        , "        if (x->len != y->len) return 0;"
        , "        const Type *element = type->aux;"
        , "        int64_t stride = words(element);"
        , "        for (int64_t i = 0; i < x->len; i++) {"
        , "            if (!tersus_equal(element, slot_value(element, x->elements + i * stride), slot_value(element, y->elements + i * stride))) return 0;"
        , "        }"
        , "        return 1;"
        , "    }"
        , "    if (type->kind == KIND_ARRAY) {"
        , "        const ArrayInfo *info = type->aux;"
        , "        const uint64_t *x = (const uint64_t *)a;"
        , "        const uint64_t *y = (const uint64_t *)b;"
        , "        int64_t step = words(info->element);"
        , "        for (int64_t i = 0; i < info->count; i++) {"
        , "            if (!tersus_equal(info->element, slot_value(info->element, x + i * step), slot_value(info->element, y + i * step))) return 0;"
        , "        }"
        , "        return 1;"
        , "    }"
        , "    if (type->kind == KIND_DATA) {"
        , "        const Data *x = (const Data *)a;"
        , "        const Data *y = (const Data *)b;"
        , "        if (x->tag != y->tag) return 0;"
        , "        const Variant *variant = &((const Variants *)type->aux)->variants[x->tag];"
        , "        int64_t at = 0;"
        , "        for (int64_t i = 0; i < variant->count; i++) {"
        , "            const Type *field = variant->fields[i].type;"
        , "            if (!tersus_equal(field, slot_value(field, x->fields + at), slot_value(field, y->fields + at))) return 0;"
        , "            at += words(field);"
        , "        }"
        , "        return 1;"
        , "    }"
        , "    return a == b;"
        , "}"
        , ""
        , "static void print_word(const Type *type, uint64_t word) {"
        , "    switch (type->kind) {"
        , "    case KIND_INT:"
        , "        printf(\"%lld\", (long long)(int64_t)word);"
        , "        break;"
        , "    case KIND_BOOL:"
        , "        fputs(word ? \"true\" : \"false\", stdout);"
        , "        break;"
        , "    case KIND_LIST: {"
        , "        const List *list = (const List *)word;"
        , "        const Type *element = type->aux;"
        , "        int64_t stride = words(element);"
        , "        putchar('[');"
        , "        for (int64_t i = 0; i < list->len; i++) {"
        , "            if (i > 0) fputs(\", \", stdout);"
        , "            print_word(element, slot_value(element, list->elements + i * stride));"
        , "        }"
        , "        putchar(']');"
        , "        break;"
        , "    }"
        , "    case KIND_ARRAY: {"
        , "        const ArrayInfo *info = type->aux;"
        , "        const uint64_t *elements = (const uint64_t *)word;"
        , "        int64_t step = words(info->element);"
        , "        putchar('[');"
        , "        for (int64_t i = 0; i < info->count; i++) {"
        , "            if (i > 0) fputs(\", \", stdout);"
        , "            print_word(info->element, slot_value(info->element, elements + i * step));"
        , "        }"
        , "        putchar(']');"
        , "        break;"
        , "    }"
        , "    case KIND_DATA: {"
        , "        const Data *data = (const Data *)word;"
        , "        const Variant *variant = &((const Variants *)type->aux)->variants[data->tag];"
        , "        fputs(variant->name, stdout);"
        , "        if (variant->count > 0) {"
        , "            fputs(\" { \", stdout);"
        , "            int64_t at = 0;"
        , "            for (int64_t i = 0; i < variant->count; i++) {"
        , "                const Type *field = variant->fields[i].type;"
        , "                if (i > 0) fputs(\", \", stdout);"
        , "                printf(\"%s: \", variant->fields[i].name);"
        , "                print_word(field, slot_value(field, data->fields + at));"
        , "                at += words(field);"
        , "            }"
        , "            fputs(\" }\", stdout);"
        , "        }"
        , "        break;"
        , "    }"
        , "    case KIND_FUNCTION:"
        , "        fputs(\"<function>\", stdout);"
        , "        break;"
        , "    }"
        , "}"
        , ""
        , "// The return value of the program, and a new line"
        , "void tersus_print(const Type *type, uint64_t word) {"
        , "    print_word(type, word);"
        , "    putchar('\\n');"
        , "}"
        ]
