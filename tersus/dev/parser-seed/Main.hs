module Main (main) where

import GHC.IO.Encoding (char8)
import System.Environment (getArgs)
import System.IO (IOMode (..), withFile, hSetEncoding, hPutStr)
import Hash (fingerprint)
import PreludeSource (parserPackageFiles, parserUnicodeSource, seedSha256)
import TersusParser (emitParserIr)
import Utils

main :: IO ()
main = do
    [output, commit] <- getArgs
    ir <- emitParserIr
    case ir of
        Error e -> fail e
        Ok text -> withFile output WriteMode $ \handle -> do
            hSetEncoding handle char8
            hPutStr handle (unlines
                [ "; Tersus native parser bootstrap seed"
                , "; source commit: " ++ commit
                , "; generated by dev/parser-seed using TersusParser.emitParserIr"
                , "; Unicode classifier fingerprint: " ++ fingerprint [parserUnicodeSource]
                , "; prepared parser PACKAGE fingerprint: " ++ fingerprint (concatMap (\(path, contents) -> [path, contents]) parserPackageFiles)
                , "; emitter seed SHA-256: " ++ seedSha256
                ] ++ text)
